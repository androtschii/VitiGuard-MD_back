DESCRIPTION = """
API системы VitiGuard MD: мониторинг здоровья виноградников Молдовы —
диагностика болезней по фото листа, спутниковые индексы Sentinel-2, риск
милдью и оидиума по погоде и предупреждения.

**Вход.** `POST /api/v1/auth/login` возвращает access-токен (15 минут) и ставит
refresh-токен в cookie `refresh_token` (HttpOnly). Токен передаётся в заголовке
`Authorization: Bearer <token>`; новый — `POST /api/v1/auth/refresh`.

**Ошибки.** Тело ошибки — `{"detail": "текст"}` на языке интерфейса; ошибки
проверки данных (422) — список полей без введённых значений.

**Ограничения частоты.** Вход, регистрация, сброс пароля и диагностика по фото
ограничены; сверх предела — 429 с заголовком `Retry-After` (секунды).

**Списки** — страницами: `?page=1&size=20` (не больше 100), в ответе
`items`, `total`, `page`, `size`, `pages`.

**Id запроса.** Каждый ответ содержит `X-Request-ID`; по нему ошибку находят
в журнале сервиса.
""".strip()

